#!/bin/sh
# Builds two variants from one source, for Sony Ericsson A200-platform phones (CLDC 1.1 / MIDP 2.0),
# into dist/<version>/ (all three go into the same GitHub release):
#   LegacyLyrion-Aino.jar     Aino: touch, docked mode, plus the standby wallpaper suite below
#   LegacyLyrion-A200.jar     keypad phones (W995, C905, W705...): no touch code, no standby
#   LegacyLyrion-Standby.jar  standby wallpaper (SEMC-StandbyApplication), from the Aino classes
# Each variant gets a generated ll/Build.java (TOUCH, VARIANT, update CHANNEL); TOUCH is a
# compile-time constant, so the A200 jar doesn't contain the touch handling at all.
# Nothing is deleted: each build compiles into its own folder, build/<version>-<date-time>/.
# The newest jars are also copied to dist/ itself, where the GitHub release workflow picks them up.
# Needs: JDK 11 or newer (runs the compiler and tools/Pack.java) and these jars in lib/, which are
# downloaded from Maven Central on the first build if missing:
#   ecj-4.6.1.jar      https://repo1.maven.org/maven2/org/eclipse/jdt/core/compiler/ecj/4.6.1/ecj-4.6.1.jar
#   cldcapi11-2.0.4.jar https://repo1.maven.org/maven2/org/microemu/cldcapi11/2.0.4/cldcapi11-2.0.4.jar
#   midpapi20-2.0.4.jar https://repo1.maven.org/maven2/org/microemu/midpapi20/2.0.4/midpapi20-2.0.4.jar
# ecj's "cldc1.1" target writes Java 1.1-era class files with the StackMap data CLDC needs,
# so no separate preverify step is required.
set -e
cd "$(dirname "$0")"
VER=${VER:-0.9.7}
# Test builds: LL_SERVER=192.168.1.20:9000 sh build.sh  -> dist-test/ with the server preset
OUT=dist
M2=https://repo1.maven.org/maven2
mkdir -p lib
for J in org/eclipse/jdt/core/compiler/ecj/4.6.1/ecj-4.6.1.jar \
         org/microemu/cldcapi11/2.0.4/cldcapi11-2.0.4.jar \
         org/microemu/midpapi20/2.0.4/midpapi20-2.0.4.jar; do
  F=lib/$(basename $J)
  if [ ! -f "$F" ]; then echo "downloading $F"; curl -fsSL -o "$F" "$M2/$J"; fi
done
if [ -n "$LL_SERVER" ]; then OUT=dist-test; fi
STAMP=$(date +%Y%m%d-%H%M%S)
B=build/$VER-$STAMP
LATEST=$OUT
OUT=$OUT/$VER
mkdir -p $B/stubs $OUT
API=lib/cldcapi11-2.0.4.jar:lib/midpapi20-2.0.4.jar
# Compile-time stubs for APIs the phone provides (JSR-256 sensors, Nokia UI DeviceControl, JSR-226 SVG, JSR-75 files); never packaged.
java -jar lib/ecj-4.6.1.jar -source 1.3 -target cldc1.1 -nowarn -bootclasspath $API \
  -d $B/stubs stubs/javax/microedition/sensor/*.java stubs/com/nokia/mid/ui/*.java stubs/javax/microedition/m2g/*.java stubs/javax/microedition/io/file/*.java

for V in Aino A200; do
  if [ $V = Aino ]; then
    TOUCH=true; CH=aino; D="Sony Ericsson Aino, 240x432 touch"
    SRC=$(ls src/ll/*.java)
  else
    TOUCH=false; CH=j2me; D="W995, C905, W705 and other 240x320 phones"
    SRC=$(ls src/ll/*.java | grep -v '/Standby\.java$')
  fi
  mkdir -p $B/$V/classes $B/$V/gen/ll
  cat > $B/$V/gen/ll/Build.java <<J
package ll;

/** Generated by build.sh: which variant this jar is. */
final class Build {
    static final boolean TOUCH = $TOUCH;
    static final String VARIANT = "$V";
    static final String CHANNEL = "$CH";
}
J
  java -jar lib/ecj-4.6.1.jar -source 1.3 -target cldc1.1 -nowarn \
    -bootclasspath $API:$B/stubs \
    -d $B/$V/classes $SRC $B/$V/gen/ll/Build.java
  cp res/icon.png $B/$V/classes/icon.png
  cat > $B/$V/MANIFEST.MF <<MF
Manifest-Version: 1.0
MIDlet-1: LegacyLyrion, /icon.png, ll.LegacyLyrion
MIDlet-Name: LegacyLyrion
MIDlet-Vendor: h33ted
MIDlet-Version: $VER
MIDlet-Icon: /icon.png
MIDlet-Description: $D
MicroEdition-Configuration: CLDC-1.1
MicroEdition-Profile: MIDP-2.0
MF
  if [ -n "$LL_SERVER" ]; then echo "LL-Server: $LL_SERVER" >> $B/$V/MANIFEST.MF; fi
  # Old Java ME installers reject wrapped (continued) manifest lines; keep every line short.
  if awk 'length > 70' $B/$V/MANIFEST.MF | grep -q .; then
    echo "ERROR: manifest line over 70 characters"; exit 1
  fi
  # Phone-friendly zip (see tools/Pack.java); the JDK jar tool's output is not accepted everywhere.
  java tools/Pack.java $OUT/LegacyLyrion-$V.jar $B/$V/MANIFEST.MF $B/$V/classes
  SIZE=$(wc -c < $OUT/LegacyLyrion-$V.jar | tr -d ' ')
  { grep -v '^Manifest-Version' $B/$V/MANIFEST.MF; echo "MIDlet-Jar-Size: $SIZE"; echo "MIDlet-Jar-URL: LegacyLyrion-$V.jar"; } > $OUT/LegacyLyrion-$V.jad
  cp $OUT/LegacyLyrion-$V.jar $OUT/LegacyLyrion-$V.jad $LATEST/
  echo "built $OUT/LegacyLyrion-$V.jar ($SIZE bytes)"
done

# Standby wallpaper: a second, light suite with the Aino classes and ll.Standby as its MIDlet.
# Sony Ericsson phones list it under Settings > Display > Wallpaper > Application.
cat > $B/STANDBY.MF <<MF
Manifest-Version: 1.0
MIDlet-1: LegacyLyrion Standby, /icon.png, ll.Standby
MIDlet-Name: LegacyLyrion Standby
MIDlet-Vendor: h33ted
MIDlet-Version: $VER
MIDlet-Icon: /icon.png
MicroEdition-Configuration: CLDC-1.1
MicroEdition-Profile: MIDP-2.0
SEMC-StandbyApplication: Y
MF
java tools/Pack.java $OUT/LegacyLyrion-Standby.jar $B/STANDBY.MF $B/Aino/classes
SSIZE=$(wc -c < $OUT/LegacyLyrion-Standby.jar | tr -d ' ')
{ grep -v '^Manifest-Version' $B/STANDBY.MF; echo "MIDlet-Description: Now playing on the standby screen"; echo "MIDlet-Jar-Size: $SSIZE"; echo "MIDlet-Jar-URL: LegacyLyrion-Standby.jar"; } > $OUT/LegacyLyrion-Standby.jad
cp $OUT/LegacyLyrion-Standby.jar $OUT/LegacyLyrion-Standby.jad $LATEST/
echo "built $OUT/LegacyLyrion-Standby.jar ($SSIZE bytes)"
